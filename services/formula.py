def calculate_result(
    s: int,
    o: int,
    l: int,
    n: int,
    f: int,
    h: int
) -> dict:
    """
    Расчёт авторской формулы:

    R = (S × O × L) - (N × F × H)
    """

    # S, O, L: от 0 до 10
    for value, name in [
        (s, "S"),
        (o, "O"),
        (l, "L")
    ]:
        if not 0 <= value <= 10:
            raise ValueError(
                f"{name} должен быть в диапазоне от 0 до 10"
            )

    # N, F, H: от 1 до 10
    for value, name in [
        (n, "N"),
        (f, "F"),
        (h, "H")
    ]:
        if not 1 <= value <= 10:
            raise ValueError(
                f"{name} должен быть в диапазоне от 1 до 10"
            )

    positive = s * o * l
    negative = n * f * h

    result = positive - negative

    return {
        "S": s,
        "O": o,
        "L": l,
        "N": n,
        "F": f,
        "H": h,
        "positive": positive,
        "negative": negative,
        "R": result
    }

def interpret_result(result: int) -> str:
    if result <= 0:
        return (
            "Ваш результат находится в зоне, где внутренние ограничения "
            "могут существенно влиять на возможность реализовывать свой потенциал."
        )

    elif result <= 100:
        return (
            "Ваш результат находится на начальном уровне и показывает, "
            "что потенциал для движения вперёд уже есть, но значительная "
            "часть ресурсов пока может использоваться не в полной мере."
        )

    elif result <= 200:
        return (
            "Ваш результат находится в среднем диапазоне. Это означает, "
            "что у вас уже сформирована определённая база для движения вперёд, "
            "но часть потенциала пока может оставаться нереализованной."
        )

    elif result <= 400:
        return (
            "Ваш результат находится в достаточно высоком диапазоне. "
            "Это говорит о том, что у вас уже сформирована сильная база "
            "для реализации своего потенциала."
        )

    else:
        return (
            "Ваш результат находится в высоком диапазоне. "
            "У вас уже сформирован значительный потенциал "
            "для дальнейшего движения и развития."
        )

def explain_positive_balance(
    s: int,
    o: int,
    l: int
) -> str | None:
    """
    Дополнительное пояснение при заметной разнице
    между показателями S, O и L.

    Если разница между максимальным и минимальным
    показателем составляет 4 балла или больше,
    добавляется нейтральное пояснение.
    """

    spread = max(s, o, l) - min(s, o, l)

    if spread < 4:
        return None

    return (
        "💡 Важный момент:\n\n"
        "Даже если вам кажется, что какая-то из составляющих "
        "сейчас выражена слабее, ваш общий результат может "
        "оставаться достаточно высоким. Это возможно потому, "
        "что сильные стороны в других областях способны "
        "компенсировать отдельные ограничения — благодаря "
        "вашему опыту, навыкам, окружению и уже сформированным "
        "инструментам.\n\n"
        "На личной встрече мы разберём, как именно ваша система "
        "формирует текущий результат и какие изменения могут "
        "дать наибольший эффект."
    )